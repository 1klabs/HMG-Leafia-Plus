#!/usr/bin/env python3
"""mkrecipe.py - turn a (stock, patched) file pair into an lpatch recipe.

usage: mkrecipe.py <id> <device-path> <stock> <patched> [--context N] [--gap N]
                   [--native MD5:note ...] [--desc "text"]

The recipe stores no bytes from the stock file:
  verify <off> <len> <md5 before> <md5 after>   region = change +/- context bytes
  patch  <off> <new hex>                        only the bytes that change
Changes closer than --gap bytes share one verify region.
"""
import argparse, hashlib, sys

ap = argparse.ArgumentParser()
ap.add_argument("id"); ap.add_argument("path"); ap.add_argument("stock"); ap.add_argument("patched")
ap.add_argument("--context", type=int, default=16)
ap.add_argument("--gap", type=int, default=16)
ap.add_argument("--native", action="append", default=[])
ap.add_argument("--desc", default="")
a = ap.parse_args()

s = open(a.stock, "rb").read(); p = open(a.patched, "rb").read()
if len(s) != len(p):
    sys.exit("stock and patched differ in size; lpatch only does in-place patches")
diff = [i for i in range(len(s)) if s[i] != p[i]]
if not diff:
    sys.exit("files are identical")
md5 = lambda b: hashlib.md5(b).hexdigest()

def runs(idx, gap):
    out = []
    for i in idx:
        if out and i - out[-1][1] <= gap:
            out[-1][1] = i
        else:
            out.append([i, i])
    return out

print(f"# {a.desc}" if a.desc else f"# {a.id}")
print(f"# generated by mkrecipe.py from stock {md5(s)} -> patched {md5(p)}")
print("# holds only hashes of the stock bytes and the new bytes written")
print(f"id {a.id}")
print(f"file {a.path}")
for n in a.native:
    m, _, note = n.partition(":")
    print(f"native {m} {note or 'native'}")
for lo, hi in runs(diff, a.gap):
    vlo = max(0, lo - a.context); vhi = min(len(s) - 1, hi + a.context)
    print(f"verify {vlo:#x} {vhi - vlo + 1} {md5(s[vlo:vhi+1])} {md5(p[vlo:vhi+1])}")
    # changed bytes only; runs are joined across stock bytes that are zero padding
    pr = []
    for i in [i for i in diff if lo <= i <= hi]:
        if pr and all(b == 0 for b in s[pr[-1][1] + 1:i]):
            pr[-1][1] = i
        else:
            pr.append([i, i])
    for clo, chi in pr:
        print(f"patch {clo:#x} {p[clo:chi+1].hex()}")
